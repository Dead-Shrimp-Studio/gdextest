import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys

from gdextest_config import (
    Config,
    discover_sources,
    find_project_root,
    godot_executable,
    godot_version,
    load_config,
    locate_extension_library,
    locate_extension_manifest,
)


